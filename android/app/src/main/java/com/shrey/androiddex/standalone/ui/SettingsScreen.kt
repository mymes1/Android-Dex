@Composable
fun ShizukuSetupCard(showInstructions: Boolean = true) {
    val context = LocalContext.current
    val state by ShizukuManager.state.collectAsStateWithLifecycle()
    DexCard(Modifier.fillMaxWidth()) {
        SectionTitle("Shizuku · optional advanced features", "Official API 13.1.5 · Wireless ADB · no root")
        StatusLine(state.label, state.authorized, state.message)
        if (state.authorized) {
            SmallText("Server API ${state.serverVersion} · UID ${state.uid} · Task bridge ${if (state.bridgeReady) "connected" else if (state.binding) "connecting" else "stopped"}")
        }
        Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            if (!state.installed) ActionButton("Install Shizuku", Icons.Default.Download) { SystemActions.shizuku(context) }
            else ActionButton("Open Shizuku", Icons.Default.OpenInNew) { if (!SystemActions.shizuku(context)) context.toast("Shizuku could not be opened") }
            ActionButton("Request permission", Icons.Default.Key, state.installed && state.binderAlive && !state.authorized) { ShizukuManager.requestPermission() }
            ActionButton("Refresh", Icons.Default.Refresh) { ShizukuManager.refresh() }
        }
        if (state.authorized) Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            TextButton(onClick = { ShizukuManager.reconnectBridge() }) { Text("Reconnect task bridge") }
            TextButton(onClick = { SystemActions.appInfo(context, context.packageName) }) { Text("App settings") }
        }
        if (showInstructions) {
            HorizontalDivider(color = DexBorder)
            WirelessInstructions()
            TextButton(onClick = { if (!SystemActions.developerOptions(context)) context.toast("Open Android Settings manually") }) { Text("Open Developer options") }
            Text("Troubleshooting: keep Wi-Fi connected during pairing; use the current pairing screen (its port changes); disable a VPN that blocks local traffic; toggle Wireless debugging off/on; update Shizuku. A denied or revoked permission must be changed inside Shizuku.", color = DexMuted, fontSize = 12.sp)
        }
    }
}

@Composable
fun AccessibilitySetupCard(vm: DesktopViewModel) {
    val context = LocalContext.current
    val accessibility by DesktopAccessibilityService.state.collectAsStateWithLifecycle()
    val settings by vm.settings.collectAsStateWithLifecycle()
    DexCard(Modifier.fillMaxWidth()) {
        SectionTitle("Accessibility · optional navigation", "Enable it yourself in Android Settings. The desktop works without it.")
        StatusLine(if (accessibility.bound) "Service enabled and bound" else if (accessibility.enabled) "Enabled · waiting for Android to bind" else "Service off", accessibility.bound)
        Text("Used for foreground-app changes, explicit Back/Home/Recents/Lock controls and an on-demand, text-free control inspector. No key-event filtering, password collection, typed-text storage or screenshots.", color = DexMuted, fontSize = 13.sp)
        ActionButton("Open Accessibility settings", Icons.Default.Accessibility) {
            if (!SystemActions.accessibility(context)) context.toast("Open Settings → Accessibility manually")
        }
        Text("Find “DeX desktop navigation” (possibly under Installed apps / Downloaded apps), enable it and approve Android's prompt.", color = DexMuted, fontSize = 12.sp)
        SettingSwitch("Floating navigation outside DeX", "A small return pill and Nav menu. Uses an accessibility overlay; no separate draw-over-apps permission is required.", settings.floatingNavigation, accessibility.bound) {
            vm.setFloatingNavigation(it)
        }
        if (accessibility.bound) TextButton(onClick = { vm.showRecents() }) { Text("Test Android Recents") }
    }
}

@Composable
fun WallpaperSettings(vm: DesktopViewModel) {
    val settings by vm.settings.collectAsStateWithLifecycle()
    val picker = rememberLauncherForActivityResult(ActivityResultContracts.PickVisualMedia()) { uri -> uri?.let(vm::importWallpaper) }
    DexCard(Modifier.fillMaxWidth()) {
        SectionTitle("Wallpaper", "Built-in gradients work offline. A selected photo is copied locally and stripped of metadata.")
        Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
            wallpaperGradients.forEachIndexed { index, colors ->
                Column(horizontalAlignment = Alignment.CenterHorizontally) {
                    Box(Modifier.size(76.dp, 48.dp).background(Brush.linearGradient(colors), RoundedCornerShape(9.dp))
                        .border(if (settings.wallpaper == index) 2.dp else 1.dp, if (settings.wallpaper == index) DexMint else DexBorder, RoundedCornerShape(9.dp))
                        .semantics { contentDescription = "Wallpaper ${wallpaperNames[index]}" }) {
                        IconButton(onClick = { vm.setWallpaper(index) }, modifier = Modifier.fillMaxSize()) {
                            if (settings.wallpaper == index) Icon(Icons.Default.Check, "Selected", tint = Color.White)
                        }
                    }
                    Text(wallpaperNames[index], fontSize = 10.sp, color = DexMuted)
                }
            }
        }
        Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            TextButton(onClick = { picker.launch(PickVisualMediaRequest(ActivityResultContracts.PickVisualMedia.ImageOnly)) }) { Text("Choose a photo") }
            if (settings.wallpaper == -1) Text("Custom photo selected", color = DexMint, fontSize = 12.sp)
        }
    }
}

private data class DisplayRow(val id: Int, val name: String, val width: Int, val height: Int, val density: Int, val refresh: Float, val publicPresentation: Boolean, val state: Int)

@Composable
fun DeviceSettings(vm: DesktopViewModel, status: SystemStatus) {
    val context = LocalContext.current
    val caps by vm.capabilities.collectAsStateWithLifecycle()
    val shizuku by ShizukuManager.state.collectAsStateWithLifecycle()
    var displays by remember { mutableStateOf(readDisplays(context)) }
    var consent by remember { mutableStateOf(false) }
    var forceResizable by remember { mutableStateOf(false) }
    DisposableEffect(context) {
        val manager = context.getSystemService(DisplayManager::class.java)
        val listener = object : DisplayManager.DisplayListener {
            override fun onDisplayAdded(displayId: Int) { displays = readDisplays(context) }
            override fun onDisplayRemoved(displayId: Int) { displays = readDisplays(context) }
            override fun onDisplayChanged(displayId: Int) { displays = readDisplays(context) }
        }
        manager.registerDisplayListener(listener, null)
        onDispose { manager.unregisterDisplayListener(listener) }
    }
    DexCard(Modifier.fillMaxWidth()) {
        SectionTitle("Device & compatibility", "Values are read from this device, not assumed from its model name.")
        InfoRow("Device", "${Build.MANUFACTURER} ${Build.MODEL}")
        InfoRow("Android", "${Build.VERSION.RELEASE} · API ${Build.VERSION.SDK_INT}")
        InfoRow("Current display", "${displays.firstOrNull { it.id == vm.displayId }?.let { "${it.width} × ${it.height} px · ${it.density} dpi · ${it.refresh} Hz" } ?: "Unavailable"}")
        InfoRow("App memory class", "${context.getSystemService(ActivityManager::class.java).memoryClass} MB${if (context.getSystemService(ActivityManager::class.java).isLowRamDevice) " · low-RAM device" else ""}")
        InfoRow("Freeform feature", if (caps.freeformFeature) "Reported by Android" else "Not reported by Android")
        InfoRow("Freeform override", caps.freeformSetting)
        InfoRow("Force-resizable override", caps.forceResizableSetting)
        InfoRow("Secondary-display feature", if (caps.secondaryDisplaysFeature) "Reported by Android" else "Not reported by Android")
        InfoRow("Shell task API", if (caps.taskApi) "Available through authorized Shizuku" else "Not verified / unavailable")
        Text(caps.probeMessage, color = DexMuted, fontSize = 12.sp)
        Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            TextButton(onClick = { ShizukuManager.refresh(); vm.probeCapabilities() }) { Text("Probe capabilities") }
            TextButton(onClick = { SystemActions.display(context) }) { Text("Android display settings") }
        }
        Text("Native freeform windows are system-owned, not embedded DeX windows. Split-screen and Recents remain Android features. Fixed-size apps and Samsung firmware may override launch requests.", color = DexMuted, fontSize = 12.sp)
        if (shizuku.bridgeReady) {
            ActionButton("Enable experimental system freeform", Icons.Default.Window, caps.taskApi) { consent = true }
            if (caps.freeformSetting == "1" || caps.forceResizableSetting == "1") TextButton(onClick = { vm.setFreeform(false, false) }) { Text("Restore both development overrides to 0") }
        }
    }
    DexCard(Modifier.fillMaxWidth()) {
        SectionTitle("Connected peripherals", "Android supplies the hardware mouse cursor. Bluetooth and USB HID devices need no extra app permission.")
        StatusLine("Physical keyboard ${if (status.keyboard) "detected" else "not detected"}", status.keyboard)
        StatusLine("Mouse ${if (status.mouse) "detected" else "not detected"} · Trackpad ${if (status.trackpad) "detected" else "not detected"}", status.mouse || status.trackpad)
        Text("Alt+Tab: switch desktop windows, then Android tasks · Super/Windows: Start · Escape: close menus · Ctrl+W: close the focused desktop window. Android may reserve some shortcuts before the app receives them.", color = DexMuted, fontSize = 12.sp)
        TextButton(onClick = { SystemActions.bluetooth(context) }) { Text("Pair Bluetooth peripherals") }
    }
    DexCard(Modifier.fillMaxWidth()) {
        SectionTitle("Android displays", "Only public presentation displays that Android exposes can be used.")
        displays.forEach { display ->
            InfoRow(display.name, "Display ${display.id} · ${display.width} × ${display.height} · ${if (display.state == Display.STATE_ON) "on" else "not active"}")
            if (display.id != vm.displayId && display.publicPresentation) {
                TextButton(onClick = { if (!SystemActions.desktop(context, display.id)) vm.notify("Android refused to launch a desktop on this display.") }) { Text("Open desktop on this display") }
            }
        }
        if (displays.none { it.id != vm.displayId && it.publicPresentation }) Text("No additional usable display is connected. SM-X110 has USB 2.0 and no MHL/DisplayPort video output; a passive USB-C HDMI adapter cannot add that hardware capability.", color = DexMuted, fontSize = 12.sp)
    }
    if (consent) AlertDialog(onDismissRequest = { consent = false }, title = { Text("Change Android development settings?") },
        text = { Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
            Text("With your authorization, Shizuku will set global enable_freeform_support=1. This is experimental and may be ignored or behave poorly on Samsung firmware.")
            SettingSwitch("Also force activities to resize", "Sets force_resizable_activities=1. Some apps may render incorrectly.", forceResizable, onChange = { forceResizable = it })
            Text("No resolution or density is changed. Restart affected apps; a reboot may be needed. You can restore both keys to 0 here.", color = DexMuted, fontSize = 12.sp)
        } },
        confirmButton = { TextButton(onClick = { consent = false; vm.setFreeform(true, forceResizable) }) { Text("Apply settings") } },
        dismissButton = { TextButton(onClick = { consent = false }) { Text("Cancel") } })
}

private fun readDisplays(context: Context): List<DisplayRow> {
    val manager = context.getSystemService(DisplayManager::class.java)
    return manager.displays.map { display ->
        val metrics = context.createDisplayContext(display).resources.displayMetrics
        DisplayRow(display.displayId, display.name, metrics.widthPixels, metrics.heightPixels, metrics.densityDpi, display.refreshRate,
            display.flags and Display.FLAG_PRESENTATION != 0 && display.flags and Display.FLAG_PRIVATE == 0, display.state)
    }
}

@Composable
fun SettingsScreen(vm: DesktopViewModel, status: SystemStatus, deviceOnly: Boolean = false, onReviewSetup: () -> Unit = {}) {
    val context = LocalContext.current
    Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(14.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
        if (deviceOnly) DeviceSettings(vm, status)
        else {
            ShizukuSetupCard()
            AccessibilitySetupCard(vm)
            WallpaperSettings(vm)
            DexCard(Modifier.fillMaxWidth()) {
                SectionTitle("Desktop behavior")
                val settings by vm.settings.collectAsStateWithLifecycle()
                SettingSwitch("Immersive desktop", "Hide Android status/navigation bars while the desktop is active. Swipe an edge to reveal them.", settings.immersive, onChange = vm::setImmersive)
                SettingSwitch("Prefer landscape", "Use sensor landscape for the desktop. Turn off to follow the tablet's rotation setting.", settings.landscape, onChange = vm::setLandscape)
                SettingSwitch("Keep screen awake in desktop", "Only while this activity is visible. Off uses the normal Android screen timeout.", settings.keepScreenOn, onChange = vm::setKeepScreenOn)
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    TextButton(onClick = vm::resetIcons) { Text("Arrange desktop icons") }
                    TextButton(onClick = { vm.reviewSetup(); onReviewSetup() }) { Text("Review first-time setup") }
                }
            }
            DeviceSettings(vm, status)
        }
        DexCard(Modifier.fillMaxWidth()) {
            SectionTitle("Privacy & local data", "No INTERNET permission, analytics, remote desktop, PC connection or root.")
            Text("Pinned apps, recent launch names, notes, layout and your selected wallpaper are stored only on this tablet. Accessibility does not retain window text or input. Shizuku is a separate app with its own privacy policy.", color = DexMuted, fontSize = 12.sp)
            Row(Modifier.horizontalScroll(rememberScrollState())) {
                TextButton(onClick = { vm.clearRecents(); vm.notify("Local recent-launch history cleared.") }) { Text("Clear recent launches") }
                TextButton(onClick = {
                    vm.preferences.savedFolder()?.let { runCatching { context.contentResolver.releasePersistableUriPermission(Uri.parse(it), Intent.FLAG_GRANT_READ_URI_PERMISSION or Intent.FLAG_GRANT_WRITE_URI_PERMISSION) } }
                    vm.preferences.saveFolder(null); vm.notify("Saved folder access released. Open Files to choose another folder.")
                }) { Text("Release folder access") }
            }
            Text("Shrey's Android DeX ${BuildConfig.VERSION_NAME} · Independent project; not affiliated with Samsung. Shizuku API by RikkaApps (MIT). Original project artwork and license retained.", color = DexMuted, fontSize = 11.sp)
            TextButton(onClick = { SystemActions.url(context, "https://github.com/RikkaApps/Shizuku-API") }) { Text("Official Shizuku API & license") }
        }
    }
}

